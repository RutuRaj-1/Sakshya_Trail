def sanitize_csv_cell(value: Any) -> str:
    """
    Defends against Spreadsheet Formula Injection (CSV Injection).
    Prefixes any string beginning with =, +, -, @, tab, or carriage return with a single quote.
    """
    if value is None:
        return ""
    s = str(value)
    if s and s[0] in ("=", "+", "-", "@", "\t", "\r"):
        return f"'{s}"
    return s


class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas for ReportLab to calculate and render 'Page X of Y' footers."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            super().showPage()
        super().save()

    def draw_page_number(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))

        # Footer Left: Sensitivity classification
        self.drawString(
            36,
            24,
            "OFFICIAL AICTE REGULATORY REPORT — SENSITIVE COMPLIANCE RECORD — UNAUTHORIZED DISCLOSURE PROHIBITED",
        )

        # Footer Right: Page numbering
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(842 - 36, 24, page_str)
        self.restoreState()


class ExportService:
    """Provides secure, audited CSV and PDF generation for operational reports."""

    ALLOWED_EXPORT_ROLES = [
        "SYSTEM_ADMIN",
        "SCRUTINY_OFFICER",
        "BRANCH_HEAD",
        "COMPETENT_AUTHORITY",
        "AUDITOR",
        "AUDIT_EXAMINER",
        "INSTITUTION_USER",
    ]

    @classmethod
    def verify_export_permission(cls, user: User) -> None:
        """Verifies that the user role has report export authorization."""
        if not user or user.role not in cls.ALLOWED_EXPORT_ROLES:
            raise AppException("User role not authorized to export reports", status_code=403, code="FORBIDDEN")

    # --------------------------------------------------------------------------
    # CSV Generator
    # --------------------------------------------------------------------------
    @classmethod
    def generate_csv(
        cls,
        db: Session,
        current_user: User,
        report_type: str,
        report_data: Dict[str, Any],
    ) -> bytes:
        """
        Generates a secure CSV with formula injection defense and metadata header block.
        Logs audit event upon generation.
        """
        cls.verify_export_permission(current_user)

        rows = report_data.get("rows", [])
        filters = report_data.get("filters_applied", {})

        output = io.StringIO()

        # Metadata Header Block
        output.write(f"# FDR Sentinel - AICTE Statutory Deposit Lifecycle Portal\n")
        output.write(f"# Report Type: {report_type}\n")
        output.write(f"# Generated At: {report_data.get('generated_at', datetime.now(timezone.utc).isoformat())}\n")
        output.write(f"# Generated By: {current_user.email} ({current_user.role})\n")
        output.write(f"# Total Records: {len(rows)}\n")
        output.write(f"# Active Filters: {json.dumps(filters)}\n")
        output.write(f"# Security Classification: CONFIDENTIAL - REGULATORY COMPLIANCE USE ONLY\n#\n")

        writer = csv.writer(output, lineterminator="\n")

        if not rows:
            writer.writerow(["Notice", "No records matched the specified filter criteria."])
        else:
            # Documented, stable column ordering per report type
            if report_type == "PENDING_VERIFICATION":
                headers = [
                    "Reference Number",
                    "Institution Name",
                    "Bank Name",
                    "Branch",
                    "Amount (INR)",
                    "Maturity Date",
                    "Trust Level",
                    "Verification Status",
                    "Source Status",
                    "Request Reference",
                    "Request Date",
                    "Pending Age (Days)",
                    "Assigned Office",
                    "Is Simulated",
                    "Has Discrepancies",
                    "Discrepancy Count",
                ]
                writer.writerow(headers)
                for r in rows:
                    writer.writerow([
                        sanitize_csv_cell(r.get("reference_number")),
                        sanitize_csv_cell(r.get("institution_name")),
                        sanitize_csv_cell(r.get("bank_name")),
                        sanitize_csv_cell(r.get("branch")),
                        sanitize_csv_cell(r.get("amount")),
                        sanitize_csv_cell(r.get("maturity_date")),
                        sanitize_csv_cell(r.get("trust_level")),
                        sanitize_csv_cell(r.get("verification_status")),
                        sanitize_csv_cell(r.get("source_status")),
                        sanitize_csv_cell(r.get("request_reference")),
                        sanitize_csv_cell(r.get("request_date")),
                        sanitize_csv_cell(r.get("pending_age_days")),
                        sanitize_csv_cell(r.get("assigned_office")),
                        sanitize_csv_cell(r.get("is_simulated")),
                        sanitize_csv_cell(r.get("has_discrepancies")),
                        sanitize_csv_cell(r.get("discrepancy_count")),
                    ])

            elif report_type == "UPCOMING_MATURITIES":
                headers = [
                    "Reference Number",
                    "Institution Name",
                    "Bank Name",
                    "Branch",
                    "Amount (INR)",
                    "Issue Date",
                    "Maturity Date",
                    "Days to Maturity",
                    "Administrative Status",
                    "Trust Level",
                    "Renewal Status",
                    "Successor Instrument ID",
                    "Assigned Office",
                ]
                writer.writerow(headers)
                for r in rows:
                    writer.writerow([
                        sanitize_csv_cell(r.get("reference_number")),
                        sanitize_csv_cell(r.get("institution_name")),
                        sanitize_csv_cell(r.get("bank_name")),
                        sanitize_csv_cell(r.get("branch")),
                        sanitize_csv_cell(r.get("amount")),
                        sanitize_csv_cell(r.get("issue_date")),
                        sanitize_csv_cell(r.get("maturity_date")),
                        sanitize_csv_cell(r.get("days_to_maturity")),
                        sanitize_csv_cell(r.get("administrative_status")),
                        sanitize_csv_cell(r.get("trust_level")),
                        sanitize_csv_cell(r.get("renewal_status")),
                        sanitize_csv_cell(r.get("successor_instrument_id")),
                        sanitize_csv_cell(r.get("assigned_office")),
                    ])

            elif report_type == "MISSING_DOCUMENTS":
                headers = [
                    "Reference Number",
                    "Institution Name",
                    "Bank Name",
                    "Assigned Office",
                    "Document Category",
                    "Policy Version",
                    "Checklist Outcome",
                    "Severity",
                    "Rule Code",
                    "Finding Title",
                    "Last Updated",
                ]
                writer.writerow(headers)
                for r in rows:
                    writer.writerow([
                        sanitize_csv_cell(r.get("reference_number")),
                        sanitize_csv_cell(r.get("institution_name")),
                        sanitize_csv_cell(r.get("bank_name")),
                        sanitize_csv_cell(r.get("assigned_office")),
                        sanitize_csv_cell(r.get("document_category")),
                        sanitize_csv_cell(r.get("policy_version")),
                        sanitize_csv_cell(r.get("checklist_outcome")),
                        sanitize_csv_cell(r.get("severity")),
                        sanitize_csv_cell(r.get("rule_id")),
                        sanitize_csv_cell(r.get("title")),
                        sanitize_csv_cell(r.get("last_updated_at")),
                    ])

            elif report_type == "INTERVENTIONS":
                headers = [
                    "Intervention Category",
                    "Reference Number",
                    "Institution Name",
                    "Reason Description",
                    "Severity",
                    "Age (Days)",
                    "Deadline Date",
                    "Assigned Office",
                    "Next Appropriate Action",
                ]
                writer.writerow(headers)
                for r in rows:
                    writer.writerow([
                        sanitize_csv_cell(r.get("intervention_type")),
                        sanitize_csv_cell(r.get("reference_number")),
                        sanitize_csv_cell(r.get("institution_name")),
                        sanitize_csv_cell(r.get("reason_description")),
                        sanitize_csv_cell(r.get("severity")),
                        sanitize_csv_cell(r.get("age_days")),
                        sanitize_csv_cell(r.get("deadline_date")),
                        sanitize_csv_cell(r.get("assigned_office")),
                        sanitize_csv_cell(r.get("next_appropriate_action")),
                    ])

        # Audit Event Log
        log_audit_event(
            db=db,
            action=f"REPORT_EXPORT_CSV_{report_type}",
            entity_type="OPERATIONAL_REPORT",
            entity_id=report_type,
            actor_user_id=current_user.id,
            actor_email=current_user.email,
            actor_role=current_user.role,
            outcome="SUCCESS",
            metadata={
                "report_type": report_type,
                "record_count": len(rows),
                "export_format": "CSV",
            },
        )

        # UTF-8 with BOM for Excel rendering
        return output.getvalue().encode("utf-8-sig")

    # --------------------------------------------------------------------------
    # PDF Generator
    # --------------------------------------------------------------------------
    @classmethod
    def generate_pdf(
        cls,
        db: Session,
        current_user: User,
        report_type: str,
        report_data: Dict[str, Any],
    ) -> bytes:
        """
        Generates a styled, landscape A4 PDF report with ReportLab.
        Logs audit event upon generation.
        """
        cls.verify_export_permission(current_user)

        rows = report_data.get("rows", [])
        filters = report_data.get("filters_applied", {})

        buf = io.BytesIO()
        doc = SimpleDocTemplate(
            buf,
            pagesize=landscape(A4),
            leftMargin=36,
            rightMargin=36,
            topMargin=36,
            bottomMargin=45,
        )

        styles = getSampleStyleSheet()

        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Title"],
            fontSize=16,
            leading=20,
            textColor=colors.HexColor("#0f172a"),
            alignment=0,
            fontName="Helvetica-Bold",
        )
        subtitle_style = ParagraphStyle(
            "DocSubTitle",
            parent=styles["Normal"],
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#475569"),
            alignment=0,
            fontName="Helvetica",
        )
        meta_style = ParagraphStyle(
            "MetaBlock",
            parent=styles["Normal"],
            fontSize=8,
            leading=11,
            textColor=colors.HexColor("#334155"),
            fontName="Helvetica",
        )
        cell_style = ParagraphStyle(
            "CellText",
            parent=styles["Normal"],
            fontSize=7.5,
            leading=9.5,
            textColor=colors.HexColor("#1e293b"),
            fontName="Helvetica",
        )
        header_cell_style = ParagraphStyle(
            "HeaderCell",
            parent=styles["Normal"],
            fontSize=8,
            leading=10,
            textColor=colors.white,
            fontName="Helvetica-Bold",
        )

        story = []

        # Header Title
        display_title = report_type.replace("_", " ").title()
        story.append(Paragraph(f"FDR Sentinel — {display_title} Report", title_style))
        story.append(Paragraph("AICTE Regulation Bureau • Statutory Security Deposit Lifecycle Platform", subtitle_style))
        story.append(Spacer(1, 10))

        # Metadata Summary Block
        gen_time = report_data.get("generated_at", datetime.now(timezone.utc).isoformat())
        meta_text = (
            f"<b>Generated:</b> {gen_time} &nbsp;|&nbsp; "
            f"<b>Requester:</b> {current_user.email} ({current_user.role}) &nbsp;|&nbsp; "
            f"<b>Total Matched Records:</b> {len(rows)} &nbsp;|&nbsp; "
            f"<b>Scope:</b> {current_user.role}"
        )
        story.append(Paragraph(meta_text, meta_style))
        story.append(Spacer(1, 12))

        # Table Construction
        if not rows:
            no_data = [[Paragraph("No records found matching the active filter criteria.", cell_style)]]
            t = Table(no_data, colWidths=[770])
            t.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f1f5f9")),
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("PADDING", (0, 0), (-1, -1), 16),
            ]))
            story.append(t)
        else:
            # Build report specific columns
            table_data = []

            if report_type == "PENDING_VERIFICATION":
                headers = ["Reference", "Institution", "Bank", "Amount (INR)", "Trust", "Status", "Age (d)", "Simulated?"]
                table_data.append([Paragraph(h, header_cell_style) for h in headers])
                col_widths = [100, 180, 110, 80, 80, 90, 50, 80]

                for r in rows:
                    sim_tag = "SIMULATED" if r.get("is_simulated") else "LIVE"
                    table_data.append([
                        Paragraph(str(r.get("reference_number") or ""), cell_style),
                        Paragraph(str(r.get("institution_name") or r.get("institution_id") or ""), cell_style),
                        Paragraph(str(r.get("bank_name") or ""), cell_style),
                        Paragraph(f"INR {r.get('amount')}", cell_style),
                        Paragraph(str(r.get("trust_level") or ""), cell_style),
                        Paragraph(str(r.get("verification_status") or ""), cell_style),
                        Paragraph(str(r.get("pending_age_days") or 0), cell_style),
                        Paragraph(sim_tag, cell_style),
                    ])

            elif report_type == "UPCOMING_MATURITIES":
                headers = ["Reference", "Institution", "Bank", "Amount (INR)", "Maturity", "Days", "Admin Status", "Trust", "Renewal Status"]
                table_data.append([Paragraph(h, header_cell_style) for h in headers])
                col_widths = [90, 160, 100, 70, 70, 45, 75, 75, 85]

                for r in rows:
                    table_data.append([
                        Paragraph(str(r.get("reference_number") or ""), cell_style),
                        Paragraph(str(r.get("institution_name") or r.get("institution_id") or ""), cell_style),
                        Paragraph(str(r.get("bank_name") or ""), cell_style),
                        Paragraph(f"INR {r.get('amount')}", cell_style),
                        Paragraph(str(r.get("maturity_date") or ""), cell_style),
                        Paragraph(str(r.get("days_to_maturity") or 0), cell_style),
                        Paragraph(str(r.get("administrative_status") or ""), cell_style),
                        Paragraph(str(r.get("trust_level") or ""), cell_style),
                        Paragraph(str(r.get("renewal_status") or ""), cell_style),
                    ])

            elif report_type == "MISSING_DOCUMENTS":
                headers = ["Reference", "Institution", "Bank", "Category", "Outcome", "Severity", "Rule", "Title"]
                table_data.append([Paragraph(h, header_cell_style) for h in headers])
                col_widths = [95, 175, 100, 95, 85, 60, 60, 100]

                for r in rows:
                    table_data.append([
                        Paragraph(str(r.get("reference_number") or ""), cell_style),
                        Paragraph(str(r.get("institution_name") or r.get("institution_id") or ""), cell_style),
                        Paragraph(str(r.get("bank_name") or ""), cell_style),
                        Paragraph(str(r.get("document_category") or ""), cell_style),
                        Paragraph(str(r.get("checklist_outcome") or ""), cell_style),
                        Paragraph(str(r.get("severity") or ""), cell_style),
                        Paragraph(str(r.get("rule_id") or ""), cell_style),
                        Paragraph(str(r.get("title") or ""), cell_style),
                    ])

            elif report_type == "INTERVENTIONS":
                headers = ["Category", "Reference", "Institution", "Reason / State", "Severity", "Age (d)", "Action Required"]
                table_data.append([Paragraph(h, header_cell_style) for h in headers])
                col_widths = [110, 95, 155, 175, 55, 45, 135]

                for r in rows:
                    table_data.append([
                        Paragraph(str(r.get("intervention_type") or ""), cell_style),
                        Paragraph(str(r.get("reference_number") or ""), cell_style),
                        Paragraph(str(r.get("institution_name") or r.get("institution_id") or ""), cell_style),
                        Paragraph(str(r.get("reason_description") or ""), cell_style),
                        Paragraph(str(r.get("severity") or ""), cell_style),
                        Paragraph(str(r.get("age_days") or 0), cell_style),
                        Paragraph(str(r.get("next_appropriate_action") or ""), cell_style),
                    ])

            t = Table(table_data, colWidths=col_widths, repeatRows=1)
            t.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f172a")),
                ("ALIGN", (0, 0), (-1, -1), "LEFT"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("LEFTPADDING", (0, 0), (-1, -1), 4),
                ("RIGHTPADDING", (0, 0), (-1, -1), 4),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ]))
            story.append(t)

        # Build PDF with two-pass canvas
        doc.build(story, canvasmaker=NumberedCanvas)

        # Audit Event Log
        log_audit_event(
            db=db,
            action=f"REPORT_EXPORT_PDF_{report_type}",
            entity_type="OPERATIONAL_REPORT",
            entity_id=report_type,
            actor_user_id=current_user.id,
            actor_email=current_user.email,
            actor_role=current_user.role,
            outcome="SUCCESS",
            metadata={
                "report_type": report_type,
                "record_count": len(rows),
                "export_format": "PDF",
            },
        )

        return buf.getvalue()
